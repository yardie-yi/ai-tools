import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const root='C:/DATA/personal/ai-tools/doc/Graph Engineering';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('file:///'+root+'/Graph_Engineering_详解.html');
await page.screenshot({path:root+'/.build/html-mobile-final.png'});
const mobile=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,decoration:getComputedStyle(document.querySelector('.hero'),'::after').display,chapters:document.querySelectorAll('section').length}));
await page.locator('#s6').scrollIntoViewIfNeeded();
await page.locator('[data-case="duplicate"]').click();
const failure=await page.locator('#fanin-status').innerText();
await page.locator('#s9').scrollIntoViewIfNeeded();
await page.locator('#overhead').fill('0');
const ideal=await page.locator('#parallel-value').innerText();
await page.locator('#concurrency').selectOption('1');
const sequential=await page.locator('#parallel-value').innerText();
await page.locator('#reset-sim').click();
await page.setViewportSize({width:1440,height:1000});
await page.evaluate(()=>scrollTo(0,0));
const desktop=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
if(mobile.scroll>mobile.width||desktop.scroll>desktop.width||mobile.decoration!=='none'||mobile.chapters!==12||ideal!=='55 s'||sequential!=='105 s'||!failure.includes('阻断')||errors.length)throw new Error(JSON.stringify({mobile,desktop,ideal,sequential,failure,errors}));
await fs.writeFile(root+'/.build/html-final-check.json',JSON.stringify({mobile,desktop,ideal,sequential,failure,errors},null,2));
console.log(JSON.stringify({mobile,desktop,ideal,sequential,errors}));
await browser.close();
